def build() -> dict[str, str]:
    pages: dict[str, str] = {"commands.md": page_commands(), "topics.md": page_topics()}
    for c in CLOUDS:
        pages[f"{c}.md"] = page_target(c)
    pages["platform-catalog.md"] = page_platform()
    pages["mcp-tools.md"] = page_mcp()
    pages["explain-index.md"] = page_explain()
    pages["skills.md"] = page_skills()
    pages["index.md"] = page_index(pages)
    for name, text in pages.items():            # nothing from this machine or run may end up in a page
        assert _SCRATCH not in text and str(paths.HOME) not in text, f"{name}: a scratch path leaked"
        assert "\x1b[" not in text, f"{name}: ANSI escape"
    return dict(sorted(pages.items()))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when a page is missing or out of date; write nothing")
    ap.add_argument("--out", default=str(OUT), help="output directory (default: docs/reference)")
    args = ap.parse_args()
    out = Path(args.out)
    pages = build()
    stale = []
    for name, text in pages.items():
        p = out / name
        if p.exists() and p.read_text() == text:
            continue
        stale.append(name)
        if not args.check:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
    if args.check:
        if stale:
            print("out of date: " + ", ".join(stale) + "  (run: python3 scripts/gen-docs.py)", file=sys.stderr)
            return 1
        print(f"docs/reference is up to date ({len(pages)} pages)")
        return 0
    print(f"{len(stale)} of {len(pages)} pages written to {out}" if stale else f"all {len(pages)} pages already up to date")
    return 0


