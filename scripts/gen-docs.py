def _first_sentence(text: str, n: int = 160) -> str:
    text = " ".join(str(text).split())
    m = re.search(r"(?<=[a-z0-9)\]])[.!?](\s|$)", text)
    if m and m.end() <= n + 1:
        return text[: m.start() + 1]
    if len(text) <= n:
        return text
    return text[: n - 1].rsplit(" ", 1)[0].rstrip(" ,;:(-") + "…"


def _explain_names() -> list[dict]:
    """[{kind, name, summary, query}] - explain.names() when this cloudseed has it (the structured explain source),
    else the same set assembled from the data `cloudseed explain` reads."""
    from cloudseed import explain
    if hasattr(explain, "lookup") and hasattr(explain, "names"):
        structured = explain.names()
        if structured and all(isinstance(n, dict) for n in structured):
            return [dict(n) for n in structured]
    names: list[dict] = []
    for f, data in explain.FEATURES.items():
        names.append({"kind": "feature", "name": f, "summary": _first_sentence(data.get("what", "")), "query": f})
    for c in CLOUDS:
        names.append({"kind": "target", "name": c, "summary": f"What cloudseed setup {c} builds, with every variable and output.",
                      "query": f"target {c}"})
    rows = overview_rows()
    aliases: dict[str, list[str]] = {}
    for a, target in sorted(helpmod.ALIASES.items()):
        aliases.setdefault(target, []).append(a)
    for c in command_order():
        if c != "help":
            name = (aliases.get(c) or [c])[0] if c not in rows else c    # `managed` is explained as `databricks`
            names.append({"kind": "command", "name": name, "summary": _command_desc(c, rows, aliases),
                          "query": f"command {name}"})
    for t in _topic_order():
        names.append({"kind": "topic", "name": t, "summary": _topic_parts(t)[0], "query": f"topic {t}"})
    for g, desc in pl.GROUPS.items():
        names.append({"kind": "group", "name": g, "summary": desc, "query": f"group {g}"})
    for i, spec in pl.CATALOG.items():
        if not spec.get("hidden"):
            names.append({"kind": "item", "name": i, "summary": spec["desc"], "query": f"item {i}"})
    return names


def page_explain() -> str:
    names = _explain_names()
    by_kind: dict[str, list[dict]] = {}
    for n in names:
        by_kind.setdefault(n["kind"], []).append(n)
    total = len(names)
    out = [front("Explain index", "Everything cloudseed explain can explain - features, cloud targets, commands, topics, "
                 "platform groups and items and every setup variable - in the CLI, the web console and over MCP."),
           "# Explain index", "",
           f"`cloudseed explain` knows **{total} pages**. Each one is available the same way everywhere: "
           "`cloudseed explain <query>` in the terminal (`--json` for data), the **?** buttons and the Explain panel "
           "in the [web console](../guides/web-console.md), and `cloudseed_explain` / `cloudseed://explain/<query>` "
           "over [MCP](../guides/mcp.md). See the [explain guide](../guides/explain.md).", "",
           generated_note("the explain index (`cloudseed/explain.py`)")]
    out += ["| Kind | Pages |", "|---|---|"]
    for k in _KIND_ORDER + tuple(sorted(set(by_kind) - set(_KIND_ORDER))):
        if by_kind.get(k):
            out.append(f"| {_KIND_TITLES.get(k, k.capitalize())} | {len(by_kind[k])} |")
    out.append("")
    for k in _KIND_ORDER + tuple(sorted(set(by_kind) - set(_KIND_ORDER))):
        entries = by_kind.get(k)
        if not entries:
            continue
        out += [f"## {_KIND_TITLES.get(k, k.capitalize())}", ""]
        if k == "variable":
            per: dict[str, list[dict]] = {}
            for n in entries:
                per.setdefault(n["name"].split()[0], []).append(n)
            out += ["Every stack variable and setup input has its own page: `cloudseed explain variable <cloud> <name>` "
                    "(or `cloudseed explain <cloud> <name>`). The full tables live on the target pages:", "",
                    "| Target | Variables | Reference |", "|---|---|---|"]
            for c in sorted(per, key=lambda c: CLOUDS.index(c) if c in CLOUDS else 99):
                out.append(f"| {CLOUD_NAMES.get(c, c)} | {len(per[c])} | [{c}]({c}.md#stack-variables) |")
            out.append("")
            continue
        out += ["| Name | What it explains | Command |", "|---|---|---|"]
        for n in entries:
            out.append(f"| `{n['name']}` | {esc(n.get('summary', ''))} | `cloudseed explain {n.get('query') or n['name']}` |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


