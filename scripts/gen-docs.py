def _schema_type(p: dict) -> str:
    if "enum" in p:
        return " \\| ".join(f"`{e}`" for e in p["enum"])
    t = p.get("type", "any")
    if t == "array":
        return f"array of {p.get('items', {}).get('type', 'any')}"
    return str(t)


def page_mcp() -> str:
    from cloudseed import mcp
    tools = mcp.tool_list()
    resources = mcp.resource_list()
    templates = mcp.resource_templates() if hasattr(mcp, "resource_templates") else []
    prompts = mcp.prompt_list()
    out = [front("MCP tools reference", f"The cloudseed MCP server's {len(tools)} tools, resources and prompts: an MCP "
                 "server for cloud infrastructure for Claude Code, Claude Desktop, Codex, Cursor and VS Code."),
           "# MCP tools reference", "",
           f"`cloudseed setup mcp` turns cloudseed into a Model Context Protocol server with **{len(tools)} tools**, "
           f"**{len(resources) + len(templates)} resources** and **{len(prompts)} prompts**. Tools marked *confirm* "
           "change infrastructure, a host or a service (or can print secrets): the server refuses them unless the call "
           "carries `confirm=true`, which a client may only send after you agreed. See the [MCP guide](../guides/mcp.md).",
           "", generated_note("the MCP server's own tool list (`cloudseed/mcp.py`)"),
           "## Tools", "", "| Tool | Confirm | What it does |", "|---|---|---|"]
    for t in tools:
        ann = t.get("annotations") or {}
        if ann.get("destructiveHint"):
            need = "always" if "Needs confirm=true" in t["description"] else "some uses"
        else:
            need = "–"
        out.append(f"| [`{t['name']}`](#{_slug(t['name'])}) | {need} | {esc(t['description'])} |")
    out.append("")
    for t in tools:
        out += [f"### {t['name']}", "", esc(t["description"]), ""]
        props = (t.get("inputSchema") or {}).get("properties") or {}
        req = set((t.get("inputSchema") or {}).get("required") or [])
        if props:
            out += ["| Argument | Type | Required | Description |", "|---|---|---|---|"]
            for name in props:
                p = props[name] or {}
                out.append(f"| `{name}` | {_schema_type(p)} | {'yes' if name in req else ''} | {esc(p.get('description', ''))} |")
            out.append("")
    out += ["## Resources", "", "| URI | Description |", "|---|---|"]
    out += [f"| `{r['uri']}` | {esc(r.get('description', ''))} |" for r in resources]
    out += [f"| `{r['uriTemplate']}` | {esc(r.get('description', ''))} |" for r in templates]
    out += ["", "## Prompts", "", "| Prompt | Arguments | Description |", "|---|---|---|"]
    for p in prompts:
        args = ", ".join(f"`{a['name']}`" + ("" if a.get("required") else " (optional)") for a in p.get("arguments", []))
        out.append(f"| `{p['name']}` | {args or '–'} | {esc(p.get('description', ''))} |")
    out += ["", "## Clients cloudseed configures", "",
            "`cloudseed mcp connect <client>` writes the client's own config (`cloudseed mcp config` prints snippets for "
            "any other client).", "", "| Client | Name for `mcp connect` | Transports | Docs |", "|---|---|---|---|"]
    for key, c in mcp.CLIENTS.items():
        out.append(f"| {esc(c['display'])} | `{key}` | {', '.join(c.get('transports', ()))} | <{c['docs']}> |")
    out.append("")
    return "\n".join(out).rstrip() + "\n"


