# ---------------------------------------------------------------- markdown helpers
def _scrub(text: str) -> str:
    """Machine-specific paths out of generated text: the private home becomes ~/.cloudseed, the checkout <repo>."""
    text = text.replace(str(paths.HOME), "~/.cloudseed")
    text = text.replace(str(paths.REPO_ROOT), "<repo>")
    return text


def esc(text: str) -> str:
    """Prose for a markdown paragraph or table cell: code spans are kept, everything else is escaped so that
    placeholders (<cloud>), pipes and asterisks render as written."""
    out = []
    for i, part in enumerate(re.split(r"(`[^`\n]+`)", str(text))):
        if i % 2:                       # a code span
            out.append(part.replace("|", "&#124;") if "|" in part else part)
            continue
        part = part.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("|", "&#124;")
        part = part.replace("*", r"\*").replace("_", r"\_").replace("[", r"\[")
        out.append(part)
    return " ".join("".join(out).split())


def code(text: str) -> str:
    """A value as inline code (a table cell): backticks cannot hold a pipe or a backtick, so those fall back to text."""
    text = " ".join(str(text).split())
    if not text:
        return "–"
    if "`" in text or "|" in text:
        return esc(text)
    return f"`{text}`"


def fence(text: str, lang: str = "text") -> str:
    body = "\n".join(line.rstrip() for line in text.strip("\n").splitlines())
    return f"```{lang}\n{body}\n```"


def front(title: str, description: str) -> str:
    # JSON strings are valid YAML double-quoted scalars: a description with ": " or "#" stays one string
    return (f"---\ntitle: {json.dumps(title, ensure_ascii=False)}\n"
            f"description: {json.dumps(description, ensure_ascii=False)}\n---\n\n"
            f"<!-- Generated by scripts/gen-docs.py from cloudseed {__version__}. Do not edit: run "
            "`python3 scripts/gen-docs.py` instead. -->\n\n")


def generated_note(source: str) -> str:
    return (f'!!! info "Generated from the code"\n    This page is generated by `scripts/gen-docs.py` from {source}, so '
            f"it always matches the CLI you install (this build: cloudseed {__version__}).\n")


# ---------------------------------------------------------------- help pages -> markdown
_HEADER_RE = re.compile(r"^[A-Z][A-Z0-9 &/<>,.'()-]{3,}$")


def _is_header(line: str) -> bool:
    s = line.rstrip()
    return bool(s) and not s.startswith(" ") and bool(_HEADER_RE.match(s)) and any(c.isalpha() for c in s) and s.upper() == s


def _title_case(header: str) -> str:
    words = header.strip().split()
    keep = {"AWS", "GCP", "VMWARE", "FIPS", "CLI", "MCP", "UI", "UIS", "VPN", "SSH", "DR", "CIS", "STIG", "TLS", "API", "CI"}
    fixed = []
    for i, w in enumerate(words):
        bare = re.sub(r"[^A-Z]", "", w)
        if bare in keep:
            fixed.append({"VMWARE": "VMware", "UIS": "UIs"}.get(bare, w))
        else:
            fixed.append(w.lower() if i else w.capitalize())
    return " ".join(fixed)


def help_body(text: str, level: str = "###") -> tuple[str, list[str]]:
    """A help page (without its synopsis) as markdown: UPPER-CASE lines become headings, prose at column 0 becomes
    paragraphs, indented blocks stay preformatted. The EXAMPLES section is returned separately (runnable commands)."""
    lines = _scrub(text).splitlines()
    examples: list[str] = []
    if "EXAMPLES" in [l.strip() for l in lines]:
        i = [l.strip() for l in lines].index("EXAMPLES")
        examples = [l.rstrip() for l in lines[i + 1:] if l.strip()]
        lines = lines[:i]
    out: list[str] = []
    pre: list[str] = []
    prose: list[str] = []

    def flush() -> None:
        if prose:
            out.append(esc(" ".join(prose)))
            out.append("")
            prose.clear()
        if pre:
            out.append(fence("\n".join(pre)))
            out.append("")
            pre.clear()

    for line in lines:
        if not line.strip():
            if pre:
                pre.append("")
            else:
                flush()
            continue
        if _is_header(line):
            flush()
            out += [f"{level} {esc(_title_case(line))}", ""]
            continue
        if line.startswith(" "):
            if prose:
                flush()
            pre.append(line)
        else:
            if pre:
                flush()
            prose.append(line.strip())
    flush()
    while out and not out[-1]:
        out.pop()
    return "\n".join(out), examples


def split_synopsis(text: str) -> tuple[str, str]:
    text = _scrub(text).strip("\n")
    parts = text.split("\n\n", 1)
    return parts[0], parts[1] if len(parts) > 1 else ""


def _overview_table() -> list[tuple[list[str], bool, str]]:
    """The command tables of the help overview as rows (commands, primary, description), in order."""
    rows: list[tuple[list[str], bool, str]] = []    # (commands, primary, description)
    section = ""
    for line in helpmod.OVERVIEW.splitlines():
        if line and not line.startswith(" "):
            section = line.strip()
            continue
        if not any(s in section for s in ("COMMANDS", "INSTALL", "INTEGRATIONS")):
            continue
        m = re.match(r"^  (\S(?:.*?\S)?)\s{2,}(\S.*)$", line)
        if m and not line.startswith("   "):
            tokens = [t for t in re.split(r"\s+", m.group(1).replace(" | ", "|")) if t]
            head = [w for w in tokens[0].split("|") if re.match(r"^[a-z][a-z0-9-]*$", w)]
            primary = all(t.startswith(("<", "[", '"')) for t in tokens[1:])
            rows.append((head, primary, m.group(2).strip()))
            continue
        cont = re.match(r"^ {10,}(\S.*)$", line)
        if cont and rows:
            words, primary, desc = rows[-1]
            rows[-1] = (words, primary, desc + " " + cont.group(1).strip())
    return rows


def _usage_rows() -> dict[str, str]:
    """command word -> description from the USAGE block of the help overview (`cloudseed help [command | topic]  this
    help, ...`): the lowest-priority source, for commands the command tables do not describe."""
    out: dict[str, str] = {}
    section = ""
    for line in helpmod.OVERVIEW.splitlines():
        if line and not line.startswith(" "):
            section = line.strip()
            continue
        m = re.match(r"^  cloudseed ([a-z][a-z0-9-]*)\b.*?\s{2,}(\S.*)$", line) if section.startswith("USAGE") else None
        if m:
            out.setdefault(m.group(1), m.group(2).strip())
    return out


def overview_rows() -> dict[str, str]:
    """command word -> one-line description, from the command tables of the help overview (the text `cloudseed help`
    prints). A row naming the command alone (`setup <cloud>`, `kubectl|helm|k9s`, `enable | disable`) wins over a row
    about one of its subcommands (`enable ui`, `setup mcp`), which only fills in a command that has no row of its own:
    the parent's (`enable`), or a command named by its second word (`enable ui` describes `ui`). The USAGE block comes
    last (`cloudseed help ...`)."""
    rows = _overview_table()
    out: dict[str, str] = {}
    for want_primary in (True, False):
        for words, primary, desc in rows:
            if primary == want_primary:
                for w in words:
                    out.setdefault(w, desc)
    for line in helpmod.OVERVIEW.splitlines():     # `enable ui   the local web console ...` -> ui
        m = re.match(r"^  ([a-z][a-z0-9-]*) ([a-z][a-z0-9-]*)\s{2,}(\S.*)$", line)
        if m and m.group(2) in helpmod.COMMANDS:
            out.setdefault(m.group(2), m.group(3).strip())
    for w, desc in _usage_rows().items():
        out.setdefault(w, desc)
    return out


def command_order() -> list[str]:
    seen: list[str] = []
    for w in [w for words, _, _ in _overview_table() for w in words]:
        page = helpmod.ALIASES.get(w, w)
        if page in helpmod.COMMANDS and page not in seen:
            seen.append(page)
    rest = sorted(c for c in helpmod.COMMANDS if c not in helpmod.ALIASES and c not in seen)
    return seen + rest


_TITLES = {"managed": "databricks / snowflake", "kubectl": "kubectl / helm / k9s"}


def _command_desc(c: str, rows: dict[str, str], aliases: dict[str, list[str]]) -> str:
    """The overview's description of a help page: its own row, else the rows of the words that open it (`databricks`
    and `snowflake` share the `managed` page: both descriptions, joined)."""
    if rows.get(c):
        return rows[c]
    descs: list[str] = []
    for a in aliases.get(c, []):
        if rows.get(a) and rows[a] not in descs:
            descs.append(rows[a])
    return "; ".join(descs)


def page_commands() -> str:
    rows = overview_rows()
