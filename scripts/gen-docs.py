_FIPS_LABEL = {"compatible": "compatible", "tls-restricted": "tls-restricted", "crypto-restricted": "crypto-restricted"}


def _source(spec: dict) -> str:
    m = spec["method"]
    if m in ("helm", "oci"):
        chart = spec["chart"]
        return f"{chart}@{spec['version']}" if spec.get("version") else chart
    if m in ("manifest", "kustomize"):
        return spec.get("url", "")
    if m == "meta":
        return "bundle: " + "; ".join(f"{k} = {', '.join(v)}" for k, v in spec.get("modes", {}).items())
    return "rendered by cloudseed"


def _needs(spec: dict) -> str:
    parts = list(spec.get("needs") or [])
    for t, ds in sorted((spec.get("needs_by_target") or {}).items()):
        parts += [f"{d} ({t})" for d in ds if d not in parts]
    return ", ".join(parts)


